import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

/**
 * Renders the React Email templates at build time. The Worker/RSC runtime
 * cannot use react-dom/server (React resolves to its react-server build), so
 * the HTML is generated here (one variant per locale) and variables are
 * substituted at runtime.
 */
process.env.BASE_URL = "__BASE_URL__";

const { render } = await import("@react-email/render");
const { EMAIL_LOCALES, MagicLinkEmail, PinResetEmail } = await import(
  "../src/email/email"
);

const magicLink: Record<string, string> = {};
for (const locale of EMAIL_LOCALES) {
  magicLink[locale] = await render(
    MagicLinkEmail({
      greetingOverride: "__GREETING__",
      locale,
      url: "__MAGIC_LINK__",
    })
  );
}

const pinReset: Record<string, string> = {};
for (const locale of EMAIL_LOCALES) {
  pinReset[locale] = await render(
    PinResetEmail({
      code: "__PIN__",
      email: "",
      greetingOverride: "__GREETING__",
    })
  );
}

const output = `// Generated by scripts/build-emails.tsx. Do not edit by hand.
// Run \`bun run email:build\` after changing src/email/email.tsx.
export const MAGIC_LINK_HTML: Record<string, string> = ${JSON.stringify(magicLink)};

export const PIN_RESET_HTML: Record<string, string> = ${JSON.stringify(pinReset)};
`;

writeFileSync(join(here, "../src/email/email-html.generated.ts"), output);
console.log(`email templates generated for ${EMAIL_LOCALES.length} locales`);
